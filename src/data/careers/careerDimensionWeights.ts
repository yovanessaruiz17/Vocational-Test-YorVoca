export const CAREER_DIMENSION_WEIGHTS: CareerDimensionWeight[] = Object.entries(
  CAREER_WEIGHT_PROFILES
).flatMap(([careerId, dimensionWeights]) =>
  Object.entries(dimensionWeights).map(([dimensionId, weight]) => ({
    careerId,
    dimensionId,
    weight,
  }))
);

export function getWeightsForCareer(careerId: string): CareerDimensionWeight[] {
  return CAREER_DIMENSION_WEIGHTS.filter((item) => item.careerId === careerId);
}

export function getWeightsForDimension(dimensionId: string): CareerDimensionWeight[] {
  return CAREER_DIMENSION_WEIGHTS.filter((item) => item.dimensionId === dimensionId);
}
